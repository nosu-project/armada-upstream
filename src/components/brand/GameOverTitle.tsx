type Run = { x: number; y: number; w: number };

function runs(bitmap: string[], dx: number): Run[] {
  const out: Run[] = [];
  bitmap.forEach((line, y) => {
    for (let c = 0; c < line.length; c++) {
      if (line[c] !== "#") continue;
      let end = c;
      while (line[end + 1] === "#") end++;
      out.push({ x: dx + c, y, w: end - c + 1 });
      c = end;
    }
  });
  return out;
}

function layout() {
  const above: Run[] = [];
  const below: Run[] = [];
  let x = 0;
  for (const ch of "GAMEOVER") {
    const glyph = GLYPHS[ch];
    for (const run of runs(glyph, x)) (run.y < CRACK ? above : below).push(run);
    x += glyph[0].length;
  }
  return { above, below, viewBox: `0 0 ${x} ${GLYPHS.G.length}` };
}

const LAYOUT = layout();

function Runs({ runs }: { runs: Run[] }) {
  return runs.map(({ x, y, w }) => <rect key={`${x},${y}`} x={x} y={y} width={w} height={1} />);
}

export function GameOverTitle({ className = "" }: { className?: string }) {
  return (
    <svg
      viewBox={LAYOUT.viewBox}
      // The attribute is the fallback where relative colour syntax isn't supported.
      fill="color-mix(in srgb, hsl(var(--primary)) 70%, white)"
      style={{ fill: "hsl(from hsl(var(--primary)) calc(h - 10) s calc(l + 8))" }}
      shapeRendering="crispEdges"
      aria-hidden="true"
      className={className}
    >
      <g fill="hsl(var(--primary))"><Runs runs={LAYOUT.above} /></g>
      <Runs runs={LAYOUT.below} />
    </svg>
  );
}
